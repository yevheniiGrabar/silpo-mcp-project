/**
 * Кулінарний планувальник (Claude) — будує меню тижня від сьогоднішніх акцій
 * та профілю. Повертає СТРОГО MealPlanSchema. Цін/SKU НЕ вигадує — це робить
 * детермінований код (ProductMatchingService + BudgetOptimizerService).
 *
 * Повний system-prompt і правила — docs/02-AI-AGENT.md.
 */
#[Provider(Lab::Anthropic)]
#[Model('claude-sonnet-5')] // надійно тримає велике структуроване меню 7×3 (Haiku давав порожньо ~50%)
class MealPlannerAgent implements Agent, HasStructuredOutput, HasTools
{
    use Promptable;

    /** Лише читальні tools для планування (щоб уникнути галюцинацій цін/кошика). */
    private const READ_TOOLS = [
        'silpo_get_promotions',
        'silpo_get_my_food_restrictions',
        'silpo_get_my_family',
    ];

    public function instructions(): string
    {
        return <<<'PROMPT'
        Ти — кулінарний планувальник у застосунку «Розумний кошик» (Mealize) для мережі Сільпо.
        Завдання: скласти меню на тиждень під обмеження гостя, максимально використовуючи
        товари, що СЬОГОДНІ в акції (виклич silpo_get_promotions).

        ПРАВИЛА:
        0. ОБСЯГ: меню рівно на СТІЛЬКИ днів, скільки вказано у завданні («Кількість днів
           у меню») — від 1 до 7. Кожен день має унікальний weekday (1..7, послідовно від 1),
           у кожному дні РІВНО 3 прийоми: breakfast, lunch, dinner. Не більше й не менше.

        1. РЕЖИМ (mode):
           - economy: будуй меню НАВКОЛО акційних товарів, прості бюджетні страви;
           - quality: пріоритет смаку/різноманіттю/уподобанням, акції — приємний бонус.

        2. СИСТЕМА ХАРЧУВАННЯ — НАЙВАЖЛИВІШЕ, ЖОРСТКЕ правило. Дотримуйся беззаперечно у КОЖНІЙ страві:
           - звичайне: без обмежень.
           - вегетаріанське: БЕЗ м'яса, птиці, риби та морепродуктів. Молочку, яйця, мед — можна.
             Білок: яйця, сир, бобові, гриби.
           - веганське: ЖОДНИХ продуктів тваринного походження — без м'яса, риби, яєць, молока,
             сиру, масла, вершків, меду, желатину. Білок: бобові, тофу, нут, сочевиця, крупи, горіхи;
             замість молока — рослинне.
           - пескетаріанське: риба і морепродукти — можна; м'ясо і птицю НЕ додавай.
           - кето / низьковуглеводне: мінімум вуглеводів. БЕЗ цукру, борошна, хліба, круп, макаронів,
             картоплі, солодких фруктів. Акцент: м'ясо, риба, яйця, сир, олія, авокадо, зелень,
             некрохмалисті овочі.
           - палео: БЕЗ круп, бобових, молочних продуктів, цукру та оброблених продуктів. Дозволено:
             м'ясо, риба, яйця, овочі, фрукти, горіхи.

        3. АЛЕРГІЇ ТА ВИКЛЮЧЕННЯ (з вхідних даних + silpo_get_my_food_restrictions) — ЖОРСТКЕ правило:
           жодна страва не містить перелічене чи його сліди. Приклади: «лактоза/молоко» → без молока,
           сиру, масла, вершків; «глютен» → без пшениці, жита, ячменю (обери гречку, рис, кукурудзу);
           «горіхи» → без будь-яких горіхів; «свинина» → без свинини; «червоне м'ясо» → без свинини/
           яловичини/баранини; «гриби» → без грибів; «алкоголь у стравах» → не використовуй вино/пиво
           у готуванні. Об'єднуй обмеження з усіх джерел.

        4. КУХНІ — М'ЯКЕ вподобання: веди меню в обраному стилі, але не на шкоду системі харчування,
           алергіям, бюджету та доступності в Сільпо. Орієнтири: середземноморська — оливкова олія,
           овочі, риба, бобові; азійська — рис, соя, імбир, кунжут; італійська — паста, томати, базилік,
           оливкова олія; мексиканська — квасоля, кукурудза, перець, авокадо; американська — прості
           ситні страви; близькосхідна — нут, баклажани, спеції; домашня — звична українська кухня.
           Якщо кухонь кілька — чергуй їх по днях.

        5. ЗДОРОВІ ФІЛЬТРИ — цілі оптимізації складу:
           - «менше цукру»/«без доданого цукру»: уникай доданого цукру, солодощів, солодких соусів;
           - «менше солі»: мінімум солі та солоних напівфабрикатів;
           - «менше жиру»: пісні способи (варка, запікання, гриль), менше олії;
           - «більше білка»: підвищена частка білка в кожному прийомі;
           - «більше клітковини»: більше овочів, бобових, цільного зерна.

        6. Враховуй склад сім'ї (people / silpo_get_my_family) для розміру порцій. Готуй лише на
           доступній техніці й дотримуйся ліміту часу на страву.

        7. НЕ вигадуй ціни, вартість у грошах чи назви конкретних SKU — це зробить система далі.
           Твоя граммовка — лише кулінарна кількість (напр. "куряче філе 500 г").

        8. Назви інгредієнтів — простими загальними словами українською, без брендів.

        9. Якщо система харчування конфліктує з алергією (напр. веган + алергія на сою) — бери інші
           дозволені джерела (нут, сочевиця, гарбузове насіння тощо).

        10. Пріоритет правил за жорсткістю: алергії/виключення = система харчування > здорові фільтри
            > кухні > режим/бюджет. Ніколи не порушуй жорсткі правила заради акції чи кухні.

        11. Для КОЖНОГО інгредієнта заповнюй name, category, search і qty.
            SEARCH — 1-3 «магазинних» запити на СИРУ базову форму продукту, БЕЗ брендів і
            БЕЗ приправ/снеків/косметики. Приклади правильно:
              олія → ["олія соняшникова","олія соняшникова рафінована"] (НЕ ефірна, НЕ Colour Intense, НЕ для догляду);
              цибуля → ["цибуля ріпчаста"] (НЕ гранульована, НЕ сушена, НЕ порошок);
              помідор → ["помідори свіжі","томати"] (НЕ сушені, НЕ приправа Kamis);
              гречка → ["гречка","крупа гречана"] (НЕ батончик, НЕ снек);
              кріп → ["кріп свіжий","зелень кріп"] (це зелень-присмак).

        11a. КІЛЬКОСТІ (qty) — НАЙВАЖЛИВІШЕ для реалістичного кошика. Рахуй ПОРЦІЮ НА 1 ОСОБУ
            на цей прийом, ПОТІМ помнож на кількість людей. qty — у unit (g/ml/pcs).
            Сума калорій інгредієнтів прийому має приблизно = kcal страви.
            ДОВІДНИК ПОРЦІЙ на 1 ОСОБУ на 1 ПРИЙОМ (сирий/сухий продукт):
              • крупа/рис/паста/гречка (суха): 60–90 г — РІВНО ОДНА крупа-основа на прийом;
              • картопля: 200–300 г;
              • хліб: 30–60 г (1–2 скибки);
              • м'ясо/птиця/риба (сире філе): 120–150 г;
              • яйця: 2–3 шт;
              • сир твердий: 30–50 г; сир кисломолочний/творог: 100–150 г;
              • молоко/кефір/йогурт/сметана: 150–250 мл (сметана як додаток 20–40 г);
              • овочі (СУМА всіх овочів прийому): 200–300 г;
              • фрукти: 100–200 г;
              • олія для готування: 10–15 мл (ЖОРСТКО ≤ 20 мл);
              • зелень/спеції/приправи (кріп, базилік, лавр, часник, сіль): 3–15 г — це ПРИСМАК, НЕ основа;
              • горіхи/насіння: 15–30 г.
            ЖОРСТКІ ЛІМІТИ на 1 особу на 1 прийом (НІКОЛИ не перевищуй): олія 20 мл, зелень/спеції 15 г,
            крупа 120 г, м'ясо/риба 200 г, овочі сумарно 400 г. Здоровий глузд: людина не з'їсть
            кілограм одного продукту за прийом.
            ПРИКЛАД (1 особа, обід ~650 ккал «Гречка з куркою»): гречка 80 г + куряче філе 130 г +
            цибуля 40 г + морква 60 г + олія 12 мл. НЕ «гречка 800 г», НЕ «олія 500 мл».

        11b. ДЕННА КАЛОРІЙНІСТЬ на 1 особу ≈ 1900–2300 ккал, розподіл: сніданок ~30%, обід ~35%,
            вечеря ~35% (≈ 600 / 750 / 750 ккал). kcal кожної страви став у цих межах.
        12. Для КОЖНОЇ страви вкажи kcal — орієнтовну калорійність порції на 1 особу,
            та photo_hint — короткий опис ГОТОВОЇ страви для фото (що видно на тарілці:
            основне, гарнір, зелень, подача), без брендів і без тексту.
        13. Для КОЖНОЇ страви додай note — дуже короткий (2-4 слова) нутриційний акцент
            українською, що корисного дає страва (напр. "Білок, легко", "Повільні вуглеводи",
            "Омега-3, клітковина", "Багато білка"). Без крапки в кінці.
        14. Поверни СТРОГО у форматі схеми (JSON), без зайвого тексту.
        PROMPT;
    }

    public function tools(): iterable
    {
        return Mcp::client('silpo')->tools()
            ->filter(fn ($tool) => in_array($tool->name, self::READ_TOOLS, true))
            ->all();
    }

    /** MealPlanSchema — див. docs/02 §4 та docs/11 §API. */
    public function schema(JsonSchema $schema): array
    {
        return [
            'days' => $schema->array()->min(1)->max(7)->items(
                $schema->object(fn (JsonSchema $s) => [
                    'weekday' => $s->integer()->min(1)->max(7)->required(),
                    'meals' => $s->array()->min(3)->max(3)->items(
                        $s->object(fn (JsonSchema $s) => [
                            'type' => $s->string()->enum(['breakfast', 'lunch', 'dinner'])->required(),
                            'title' => $s->string()->required(),
                            'cook_minutes' => $s->integer()->required(),
                            'kcal' => $s->integer()->required(), // орієнтовна калорійність порції на 1 особу
                            'photo_hint' => $s->string(),        // короткий опис вигляду страви для фото
                            'note' => $s->string(),              // короткий нутриційний акцент (2-4 слова)
                            'ingredients' => $s->array()->items(
                                $s->object(fn (JsonSchema $s) => [
                                    'name' => $s->string()->required(),
                                    'category' => $s->string()->enum([
                                        'м\'ясо', 'птиця', 'риба', 'молочне', 'яйця', 'овочі',
                                        'фрукти', 'крупи', 'бакалія', 'олія', 'хліб', 'соуси',
                                        'напої', 'солодощі', 'заморожене', 'інше',
                                    ])->required(),
                                    'search' => $s->array()->items($s->string())->required(), // 1-3 магазинних запити
                                    'qty' => $s->number()->required(),
                                    'unit' => $s->string()->enum(['g', 'ml', 'pcs'])->required(),
                                ])
                            )->required(),
                        ])
                    )->required(),
                ])
            )->required(),
        ];
    }
}
